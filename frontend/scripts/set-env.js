/**
 * set-env.js — Pre-build script for Vercel deployment
 *
 * Reads environment variables set in the Vercel dashboard and writes them
 * into src/environments/environment.prod.ts before Angular compiles.
 *
 * Required Vercel Environment Variables:
 *   KEYCLOAK_URL          e.g.  http://<your-ec2-public-ip>:8180
 *   KEYCLOAK_REALM        e.g.  citizen-portal
 *   KEYCLOAK_CLIENT_ID    e.g.  citizen-portal-client
 *   API_GATEWAY_URL       e.g.  http://<your-ec2-public-ip>:8080
 *
 * Usage (called automatically by the Vercel build command):
 *   node scripts/set-env.js
 */

const fs = require('fs');
const path = require('path');

const targetPath = path.join(__dirname, '..', 'src', 'environments', 'environment.prod.ts');

// Read from Vercel / CI environment variables
const keycloakUrl      = process.env.KEYCLOAK_URL       || 'http://localhost:8180';
const keycloakRealm    = process.env.KEYCLOAK_REALM     || 'citizen-portal';
const keycloakClientId = process.env.KEYCLOAK_CLIENT_ID || 'citizen-portal-client';
const apiGatewayUrl    = process.env.API_GATEWAY_URL    || 'http://localhost:8080';

const envFileContent = `/**
 * Production environment — AUTO-GENERATED by scripts/set-env.js
 * Do NOT edit manually. Values come from Vercel Environment Variables.
 */
export const environment = {
  production: true,
  keycloak: {
    url: '${keycloakUrl}',
    realm: '${keycloakRealm}',
    clientId: '${keycloakClientId}',
  },
  apiGatewayUrl: '${apiGatewayUrl}',
};
`;

fs.writeFileSync(targetPath, envFileContent);
console.log(`✅  environment.prod.ts written with:`);
console.log(`    Keycloak URL    : ${keycloakUrl}`);
console.log(`    Keycloak Realm  : ${keycloakRealm}`);
console.log(`    Client ID       : ${keycloakClientId}`);
console.log(`    API Gateway URL : ${apiGatewayUrl}`);

